import re
import urllib.request
import io
from collections import Counter
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from matplotlib.gridspec import GridSpec
from wordcloud import WordCloud, STOPWORDS
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.model_selection import train_test_split
from sklearn.naive_bayes import MultinomialNB
from sklearn.metrics import accuracy_score,confusion_matrix

# 1. LOAD DATA (auto-downloads the dataset — no manual file needed)
DATA_URL = (
    "https://raw.githubusercontent.com/Prodigy-InfoTech/"
    "data-science-datasets/main/Task%204/twitter_training.csv"
)
print("Downloading Twitter sentiment dataset...")
with urllib.request.urlopen(DATA_URL) as response:
    raw_bytes = response.read()
    df = pd.read_csv(
        io.BytesIO(raw_bytes),
        header=None,
        names=["tweet_id", "entity", "sentiment", "text"],
    )
print(f"Raw dataset shape: {df.shape}")

# 2. CLEANING & PREPROCESSING
df = df.dropna(subset=["text"]).copy()
df = df.drop_duplicates(subset=["text", "entity", "sentiment"])

def clean_text(text: str) -> str:
    text = str(text).lower()
    text = re.sub(r"http\S+|www\.\S+", " ", text) # URLs
    text = re.sub(r"@\w+", " ", text) # mentions
    text = re.sub(r"#(\w+)", r"\1", text) # hashtags -> word
    text = re.sub(r"[^a-z\s]", " ", text) # punctuation/numbers
    text = re.sub(r"\s+", " ", text).strip()
    return text

df["clean_text"] = df["text"].apply(clean_text)
df = df[df["clean_text"].str.len() > 0]
print(f"Cleaned dataset shape: {df.shape}")
print(f"Sentiment classes: {df['sentiment'].unique().tolist()}")
print(f"Entities tracked: {df['entity'].nunique()}")

# 3. SENTIMENT PATTERN ANALYSIS
sentiment_counts = df["sentiment"].value_counts()
top_entities = df["entity"].value_counts().head(10).index
entity_sentiment = (
    df[df["entity"].isin(top_entities)]
    .groupby(["entity", "sentiment"])
    .size()
    .unstack(fill_value=0)
    .loc[top_entities]
)
entity_sentiment_pct = entity_sentiment.div(entity_sentiment.sum(axis=1), axis=0) * 100
df["word_count"] = df["clean_text"].str.split().str.len()
avg_len_by_sentiment = df.groupby("sentiment")["word_count"].mean()
STOP = set(STOPWORDS)

def top_words(series, n=15):
    words = " ".join(series).split()
    words = [w for w in words if w not in STOP and len(w) > 2]
    return Counter(words).most_common(n)

positive_words = top_words(df.loc[df["sentiment"] == "Positive", "clean_text"])
negative_words = top_words(df.loc[df["sentiment"] == "Negative", "clean_text"])

# 4. SIMPLE VALIDATION CLASSIFIER (TF-IDF + Naive Bayes)
X_train, X_test, y_train, y_test = train_test_split(
    df["clean_text"], df["sentiment"],
    test_size=0.2, random_state=42,
    stratify=df["sentiment"]
)

vectorizer = TfidfVectorizer(max_features=8000, ngram_range=(1, 2), min_df=3)
X_train_vec = vectorizer.fit_transform(X_train)
X_test_vec = vectorizer.transform(X_test)
clf = MultinomialNB()
clf.fit(X_train_vec, y_train)
y_pred = clf.predict(X_test_vec)
accuracy = accuracy_score(y_test, y_pred)
labels_order = sorted(df["sentiment"].unique())
cm = confusion_matrix(y_test, y_pred, labels=labels_order)
print(f"\nValidation classifier (TF-IDF + Naive Bayes) accuracy: {accuracy:.4f}")

