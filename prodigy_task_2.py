# 1. LOAD DATA
# ----------------------------------------------
def load_data():
  if not os.path.exists(LOCAL_PATH):
    print("Downloading dataset from Prodigy-InfoTech GitHub repo...")
    urllib.request.urlretrieve(DATA_URL, LOCAL_PATH)
  df = pd.read_csv(LOCAL_PATH)
  print(f"Loaded {df.shape[0]} rows x{df.shape[1]} columns.\n")
  return df

df = load_data()

# 2. DATA CLEANING
# ----------------------------------------------
# --------------------
def clean_data(df):
  df = df.copy() # Make a copy to avoid modifying the original DataFrame
  print("Missing values BEFORE cleaning:")
  print(df.isnull().sum()[df.isnull().sum() > 0], "\n")

  # Duplicates
  dup_count = df.duplicated().sum()
  if dup_count:
    df = df.drop_duplicates()
  print(f"Duplicate rows removed:{dup_count}")

  # Age -> fill with median per Pclass/Sex group (more realistic than a single global median)
  df["Age"] = df.groupby(["Pclass", "Sex"])["Age"].transform(
      lambda x: x.fillna(x.median())
  )
  df["Age"] = df["Age"].fillna(df["Age"].median())

  # Embarked -> fill with mode
  df["Embarked"] = df["Embarked"].fillna(df["Embarked"].mode()[0])

  # Fare -> fill with median (if any missing)
  df["Fare"] = df["Fare"].fillna(df["Fare"].median())

  # Cabin -> mostly missing; convert to a binary "HasCabin" flag instead of dropping the column
  df["HasCabin"] = df["Cabin"].notna().astype(int)
  df = df.drop(columns=["Cabin"])

  # Dtypes
  df["Survived"] = df["Survived"].astype(int)
  df["Pclass"] = df["Pclass"].astype(int)

  # Feature engineering
  df["FamilySize"] = df["SibSp"] + df["Parch"] + 1
  df["IsAlone"] = (df["FamilySize"] == 1).astype(int)
  df["Title"] = df["Name"].str.extract(r",\s*([^.]*)\.")
  rare_titles = df["Title"].value_counts()[df["Title"].value_counts() < 10].index
  df["Title"] = df["Title"].replace(rare_titles, "Rare")

  df["AgeGroup"] = pd.cut(
      df["Age"], bins=[0, 12, 18, 35, 60, 100],
      labels=["Child", "Teen", "Adult", "MiddleAge", "Senior"]
  )
  df["FareBand"] = pd.qcut(df["Fare"], 4,
                           labels=["Low", "Mid", "High", "VeryHigh"])

  print("\nMissing values AFTER cleaning:")
  print(df.isnull().sum()[df.isnull().sum() > 0] if df.isnull().sum().sum() else "None remaining.")
  print(f"\nFinal shape: {df.shape}\n")
  return df

# Call the clean_data function
df = clean_data(df)

# 3. EDA -> PRINTED INSIGHTS
# ------------------------------------------------------------------
def print_insights(df):
  print("=" * 60)
  print("KEY INSIGHTS")
  print("=" * 60)
  overall = df["Survived"].mean() * 100
  print(f"Overall survival rate:{overall:.1f}%")

  by_sex = df.groupby("Sex")["Survived"].mean() * 100
  print(f"Survival by sex: female {by_sex.get('female', 0):.1f}% | " f"male {by_sex.get('male', 0):.1f}%")
  by_class = df.groupby("Pclass")["Survived"].mean() * 100
  print("Survival by class:", ", ".join(f"Class {c}: {v:.1f}%" for c, v in by_class.items()))
  by_alone = df.groupby("IsAlone")["Survived"].mean() * 100
  print(f"Survival - traveling alone:{by_alone.get(1, 0):.1f}% | with family: {by_alone.get(0,0):.1f}%")

  corr_age_survival = df["Age"].corr(df["Survived"])
  corr_fare_survival = df["Fare"].corr(df["Survived"])
  print(f"Correlation Age~Survived: {corr_age_survival:.3f}")
  print(f"Correlation Fare~Survived: {corr_fare_survival:.3f}")
  print("=" * 60, "\n")

print_insights(df)

# 4. DASHBOARD (dark theme, multi-panel)
# ------------------------------------------------------------------
def build_dashboard(df):
  fig = plt.figure(figsize=(20, 22))
  fig.patch.set_facecolor(BG)
  gs = gridspec.GridSpec(5, 2, figure=fig, hspace=0.55, wspace=0.28)
  fig.suptitle("TITANIC DATASET — DATA CLEANING & EXPLORATORY ANALYSIS", fontsize=22, fontweight="bold", color=TEXT, y=0.995)
  fig.text(0.5, 0.978, "Prodigy InfoTech Data Science Internship · Task 2", ha="center", fontsize=12, color=MUTED)

  def style_ax(ax, title):
    ax.set_title(title, fontsize=13, fontweight="bold", color=TEXT, pad=10)
    ax.grid(alpha=0.25, linewidth=0.5)
    for spine in ax.spines.values():
      spine.set_color(GRID)

  # 1. Survival count
  ax1 = fig.add_subplot(gs[0, 0])
  counts = df["Survived"].value_counts().sort_index()
  bars = ax1.bar(["Did not survive", "Survived"], counts.values, color=[RED, GREEN], width=0.55)
  for b in bars:
    ax1.text(b.get_x() + b.get_width() / 2, b.get_height() + 5, f"{int(b.get_height())}", ha="center", color=TEXT, fontsize=10)
  style_ax(ax1, "Survival Count")

  # 2. Survival rate by sex
  ax2 = fig.add_subplot(gs[0, 1])
  sex_surv = df.groupby("Sex")["Survived"].mean() * 100
  bars = ax2.bar(sex_surv.index, sex_surv.values, color=[RED, BLUE], width=0.5)
  for b in bars:
    ax2.text(b.get_x() + b.get_width() / 2, b.get_height() + 1, f"{b.get_height():.1f}%", ha="center", color=TEXT, fontsize=10)
  ax2.set_ylabel("Survival rate (%)")
  style_ax(ax2, "Survival Rate by Sex")

  # 3. Survival rate by class
  ax3 = fig.add_subplot(gs[1, 0])
  class_surv = df.groupby("Pclass")["Survived"].mean() * 100
  bars = ax3.bar(class_surv.index.astype(str), class_surv.values, color=PALETTE[:3], width=0.5)
  for b in bars:
    ax3.text(b.get_x() + b.get_width() / 2, b.get_height() + 1, f"{b.get_height():.1f}%", ha="center", color=TEXT, fontsize=10)
  ax3.set_xlabel("Passenger Class")
  ax3.set_ylabel("Survival rate (%)")
  style_ax(ax3, "Survival Rate by Passenger Class")

  # 4. Age distribution by survival
  ax4 = fig.add_subplot(gs[1, 1])
  sns.kdeplot(df[df["Survived"] == 0]["Age"], ax=ax4, color=RED, fill=True, alpha=0.35, label="Did not survive")
  sns.kdeplot(df[df["Survived"] == 1]["Age"], ax=ax4, color=GREEN, fill=True, alpha=0.35, label="Survived")
  ax4.set_xlabel("Age")
  ax4.legend(facecolor=PANEL, edgecolor=GRID, labelcolor=TEXT, fontsize=9)
  style_ax(ax4, "Age Distribution by Survival")

  # 5. Fare distribution by class (boxplot)
  ax5 = fig.add_subplot(gs[2, 0])
  sns.boxplot(data=df, x="Pclass", y="Fare",
  ax=ax5,
  palette=PALETTE[:3],
  hue="Pclass", legend=False)
  ax5.set_xlabel("Passenger Class")
  style_ax(ax5, "Fare Distribution by Class")
  # 6. Family size vs survival
  ax6 = fig.add_subplot(gs[2, 1])
  fam_surv = df.groupby("FamilySize")\
  ["Survived"].mean() * 100
  ax6.plot(fam_surv.index, fam_surv.values,
  marker="o", color=YELLOW,
  linewidth=2, markersize=6,
  markerfacecolor=BLUE)
  ax6.set_xlabel("Family Size")
  ax6.set_ylabel("Survival rate (%)")
  style_ax(ax6, "Survival Rate by Family\nSize")
  # 7. Embarked counts vs survival
  ax7 = fig.add_subplot(gs[3, 0])
  embarked_ct = pd.crosstab(df["Embarked"],
df["Survived"])
  embarked_ct.columns = ["Did not survive",
  "Survived"]
  embarked_ct.plot(kind="bar", stacked=True,
  ax=ax7, color=[RED, GREEN], width=0.6)
  ax7.set_xlabel("Port of Embarkation")
  ax7.tick_params(axis="x", rotation=0)
  ax7.legend(facecolor=PANEL, edgecolor=GRID,
  labelcolor=TEXT, fontsize=9)
  style_ax(ax7, "Embarkation Port vs\nSurvival")
  # 8. Title distribution
  ax8 = fig.add_subplot(gs[3, 1])
  title_ct = df["Title"].value_counts()
  ax8.barh(title_ct.index[::-1],
title_ct.values[::-1], color=BLUE)
  ax8.set_xlabel("Count")
  style_ax(ax8, "Passenger Title\nDistribution")
  # 9. Correlation heatmap
  ax9 = fig.add_subplot(gs[4, 0])
  num_cols = ["Survived", "Pclass", "Age",
  "SibSp", "Parch", "Fare",
  "FamilySize", "HasCabin"]
  corr = df[num_cols].corr()
  sns.heatmap(corr, ax=ax9, cmap="coolwarm",
  center=0, annot=True, fmt=".2f",
  annot_kws={"size": 7, "color":
  "black"}, cbar=False,
  linewidths=0.5, linecolor=BG)
  ax9.set_xticklabels(ax9.get_xticklabels(),
  rotation=45, ha="right", fontsize=8)
  ax9.set_yticklabels(ax9.get_yticklabels(),
  rotation=0, fontsize=8)
  style_ax(ax9, "Correlation Heatmap")
  # 10. Age group vs survival
  ax10 = fig.add_subplot(gs[4, 1])
  ag_surv = df.groupby("AgeGroup",
  observed=True)["Survived"].mean() * 100
  bars = ax10.bar(ag_surv.index.astype(str),
ag_surv.values, color=PALETTE * 2)
  for b in bars:
      ax10.text(b.get_x() + b.get_width() / 2,
      b.get_height() + 1,
      f"{b.get_height():.0f}%",
      ha="center", color=TEXT, fontsize=9)
  ax10.set_ylabel("Survival rate (%)")
  ax10.tick_params(axis="x", rotation=15)
  style_ax(ax10, "Survival Rate by Age Group")
  fig.text(0.5, 0.005,
  """Data source: Prodigy-InfoTech/data-science-datasets (Task 2) · \
Original: Kaggle Titanic Competition""",
  ha="center", fontsize=9,
  color=MUTED)

  plt.tight_layout()
  plt.savefig(OUTPUT_PNG, dpi=150,
  facecolor=BG, bbox_inches="tight")
  print(f"Dashboard saved to: {OUTPUT_PNG}")
  plt.close(fig)
  plt.show()

build_dashboard(df)

