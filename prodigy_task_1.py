import pandas as pd
import matplotlib.pyplot as plt
import numpy as np

# 1. LOAD DATA — pulled straight from the Prodigy InfoTech GitHub repo
DATA_URL = ("https://raw.githubusercontent.com/Prodigy-InfoTech/"

"data-science-datasets/main/Task%201/"
"API_SP.POP.TOTL_DS2_en_csv_v2_38144.csv"
)
# The World Bank CSV has 4 metadata rows before the real header
df = pd.read_csv(DATA_URL, skiprows=4)

#2. CLEAN DATA
LATEST_YEAR = "2023" # most recent column with complete-ish data in this file
# World Bank includes aggregate regions (World,income groups, etc.) mixed
# in with actual countries. Filter those out using the region metadata file.
META_URL = ("https://raw.githubusercontent.com/Prodigy-InfoTech/"
"data-science-datasets/main/Task%201/"
"Metadata_Country_API_SP.POP.TOTL_DS2_en_csv_v2_38144.csv"
)
meta = pd.read_csv(META_URL)
real_countries = meta.loc[meta["Region"].notna(), "Country Code"]
df_clean = df[df["Country Code"].isin(real_countries)].copy()
df_clean = df_clean[["Country Name", "Country Code", LATEST_YEAR]].dropna()
df_clean.rename(columns={LATEST_YEAR:"Population"}, inplace=True)
df_clean["Population"] = df_clean["Population"].astype(float)
print(f"Countries after cleaning:{len(df_clean)}")
print(df_clean.sort_values("Population",
ascending=False).head(10))

# 3. DARK-THEMED DASHBOARD (bar chart of top
# countries + histogram)
# ----------------------------------------------------------------------
import os
import matplotlib.pyplot as plt

plt.rcParams["figure.facecolor"] = "#0d0d1a"
plt.rcParams["axes.facecolor"] = "#0d0d1a"
plt.rcParams["text.color"] = "white"
plt.rcParams["axes.labelcolor"] = "white"
plt.rcParams["xtick.color"] = "white"
plt.rcParams["ytick.color"] = "white"
plt.rcParams["axes.edgecolor"] = "#444466"
ACCENT_BLUE = "#3ba7ff"
ACCENT_RED = "#ff5c5c"
ACCENT_GREEN = "#4be38a"
fig, axes = plt.subplots(1, 2, figsize=(16, 7))
fig.suptitle(
    "Task 01 — Population Distribution (World Bank Data)",
    fontsize=18, fontweight="bold",
    color="white"
)
# --- Panel 1: Bar chart of top 15 most populous countries ---
top15 = df_clean.sort_values("Population",
                            ascending=False).head(15)
colors = [ACCENT_BLUE if i % 2 == 0 else
          ACCENT_RED for i in range(len(top15))]
axes[0].barh(top15["Country Name"][::-1],
             top15["Population"][::-1] / 1e6,
             color=colors[::-1],
             edgecolor="white", linewidth=0.4)
axes[0].set_title("Top 15 Countries by Population (2023)", color="white", fontsize=13)
axes[0].set_xlabel("Population (millions)")
axes[0].grid(axis="x", color="#333355",
             alpha=0.5)
# --- Panel 2: Histogram of population distribution (all countries) ---
axes[1].hist(df_clean["Population"] / 1e6,
             bins=30,
             color=ACCENT_GREEN,
             edgecolor="#0d0d1a", alpha=0.9)
axes[1].set_title("Distribution of Population Across Countries (2023)", color="white",
                  fontsize=13)
axes[1].set_xlabel("Population (millions)")
axes[1].set_ylabel("Number of Countries")
axes[1].set_yscale("log") # population is heavily right-skewed
axes[1].grid(axis="y", color="#333355",
             alpha=0.5)
plt.tight_layout(rect=[0, 0, 1, 0.95])

# Ensure output directory exists
os.makedirs("/mnt/user-data/outputs", exist_ok=True)

plt.savefig("/mnt/user-data/outputs/task1_population_distribution.png",
            dpi=150,
            facecolor=fig.get_facecolor())
plt.show()
print("\nDashboard saved to task1_population_distribution.png")